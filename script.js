// GENRE EVENT

document.getElementById("genre")
    ?.addEventListener("change", refresh);

// CATEGORY EVENT

document.getElementById("type")
    ?.addEventListener("change", refresh);

// OPEN MOVIE DETAILS

function openMovie(id) {

    selectedMovie = movies.find(movie => movie.id === id);

    if (!selectedMovie) return;

    document.getElementById("detailTitle").textContent =
        selectedMovie.title;

    document.getElementById("detailPosterTitle").textContent =
        selectedMovie.title;

    document.getElementById("detailType").textContent =
        selectedMovie.type.toUpperCase();

    document.getElementById("detailMeta").textContent =
        selectedMovie.genre + " · " + selectedMovie.year;

    document.getElementById("detailDescription").textContent =
        selectedMovie.description;

    document.getElementById("detailPoster").style.background =
        `linear-gradient(140deg,${selectedMovie.color},#20213e),
         url("${selectedMovie.image}") center/cover`;

    // RESET VIDEO PLAYER

    const frame = document.getElementById("trailerFrame");

    const player = document.getElementById("moviePlayer");

    frame.src = "";

    frame.hidden = false;

    player.pause();

    player.removeAttribute("src");

    player.load();

    player.hidden = true;

    document.getElementById("videoArea").hidden = true;

    // UPDATE WATCHLIST BUTTON

    document.querySelector(".add").textContent =

        saved.includes(id)
            ? "✓ Remove from My List"
            : "＋ Add to My List";

    document.getElementById("movieModal")
        .classList.add("active");

}

// CLOSE MOVIE DETAILS

function closeMovie() {

    document.getElementById("movieModal")
        .classList.remove("active");

    const frame = document.getElementById("trailerFrame");

    const player = document.getElementById("moviePlayer");

    frame.src = "";

    player.pause();

    player.removeAttribute("src");

    player.load();

    player.hidden = true;

    document.getElementById("videoArea").hidden = true;

    selectedMovie = null;

}

// WATCH TRAILER

function watchTrailer() {

    if (!selectedMovie) return;

    if (!selectedMovie.trailer) {

        showToast("Trailer has not been added yet.");

        return;

    }

    const area = document.getElementById("videoArea");

    const player = document.getElementById("moviePlayer");

    const frame = document.getElementById("trailerFrame");

    player.pause();

    player.removeAttribute("src");

    player.load();

    player.hidden = true;

    frame.hidden = false;

    frame.src = selectedMovie.trailer;

    area.hidden = false;

    area.scrollIntoView({
        behavior: "smooth",
        block: "nearest"
    });

}

// WATCH MOVIE

function watchNow() {

    if (!selectedMovie) return;

    if (!selectedMovie.video) {

        showToast("Movie video has not been added yet.");

        return;

    }

    const area = document.getElementById("videoArea");

    const frame = document.getElementById("trailerFrame");

    const player = document.getElementById("moviePlayer");

    frame.src = "";

    frame.hidden = true;

    player.hidden = false;

    player.src = selectedMovie.video;

    area.hidden = false;

    player.play().catch(() => {

        showToast("Press play to start the video.");

    });

    area.scrollIntoView({
        behavior: "smooth",
        block: "nearest"
    });

}

// DOWNLOAD MOVIE

function downloadMovie() {

    if (!selectedMovie) return;

    if (!selectedMovie.download) {

        showToast("Download file has not been added yet.");

        return;

    }

    const link = document.createElement("a");

    link.href = selectedMovie.download;

    link.download = selectedMovie.title + ".mp4";

    document.body.appendChild(link);

    link.click();

    link.remove();

}

// ADD OR REMOVE FROM MY LIST

function toggleList() {

    if (!selectedMovie) return;

    const id = selectedMovie.id;

    if (saved.includes(id)) {

        saved = saved.filter(item => item !== id);

        showToast("Removed from My List");

    } else {

        saved.push(id);

        showToast("Added to My List");

    }

    localStorage.setItem(
        "ralepomaSaved",
        JSON.stringify(saved)
    );

    document.querySelector(".add").textContent =

        saved.includes(id)
            ? "✓ Remove from My List"
            : "＋ Add to My List";

    displaySaved();

}

// DISPLAY SAVED MOVIES

function displaySaved() {

    const list = movies.filter(movie =>
        saved.includes(movie.id)
    );

    displayMovies(list, "savedContainer");

    const count = document.getElementById("savedCount");

    const empty = document.getElementById("emptyList");

    if (count) {

        count.textContent = list.length + " saved";

    }

    if (empty) {

        empty.hidden = list.length > 0;

    }

}

// NOTIFICATION

let toastTimer;

function showToast(message) {

    const toast = document.getElementById("toast");

    if (!toast) return;

    toast.textContent = message;

    toast.style.display = "block";

    clearTimeout(toastTimer);

    toastTimer = setTimeout(() => {

        toast.style.display = "none";

    }, 2500);

}

// SIGN IN

function openForm() {

    document.getElementById("formModal")
        .classList.add("active");

}

function closeForm() {

    document.getElementById("formModal")
        .classList.remove("active");

}

document.getElementById("loginForm")
    ?.addEventListener("submit", function(event) {

        event.preventDefault();

        const email = document.getElementById("email").value.trim();

        const password = document.getElementById("password").value;

        const message = document.getElementById("loginMessage");

        if (!email || !password) {

            message.textContent = "Please fill in all fields.";

            return;

        }

        if (password.length < 4) {

            message.textContent = "Password must have at least 4 characters.";

            return;

        }

        message.textContent =
            "Demo form validated successfully!";

        showToast("Sign in form validated.");

    });

// CLOSE MODALS BY CLICKING OUTSIDE

document.getElementById("movieModal")
    ?.addEventListener("click", function(event) {

        if (event.target === this) {

            closeMovie();

        }

    });

document.getElementById("formModal")
    ?.addEventListener("click", function(event) {

        if (event.target === this) {

            closeForm();

        }

    });


// CLOSE MODALS WITH ESCAPE KEY

document.addEventListener("keydown", function(event) {

    if (event.key === "Escape") {

        closeMovie();

        closeForm();

    }

});

