// DISPLAY HERO ADVERTISEMENT

function showHero(index) {

    const hero = document.getElementById("hero");

    const title = document.getElementById("heroTitle");

    const description = document.getElementById("heroDescription");

    const label = document.getElementById("heroLabel");

    const dots = document.getElementById("heroDots");

    if (!hero || !title || !description || !dots) return;

    currentHero = (index + heroAds.length) % heroAds.length;

    const ad = heroAds[currentHero];

    hero.style.backgroundImage = `

        linear-gradient(
            90deg,
            rgba(25,18,55,0.95),
            rgba(40,25,85,0.55),
            rgba(0,0,0,0.15)
        ),

        url("${ad.image}")

    `;

    title.textContent = ad.title;

    description.textContent = ad.description;

    if (label) {

        label.textContent = ad.label;

    }

    // CREATE NAVIGATION DOTS

    dots.innerHTML = "";

    heroAds.forEach((item, i) => {

        const dot = document.createElement("button");

        dot.className = "hero-dot";

        if (i === currentHero) {

            dot.classList.add("active");

        }

        dot.setAttribute(
            "aria-label",
            "Show advertisement " + (i + 1)
        );

        dot.addEventListener("click", () => {

            showHero(i);

            restartHeroTimer();

        });

        dots.appendChild(dot);

    });

}

// NEXT ADVERTISEMENT

