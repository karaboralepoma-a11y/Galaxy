// VARIABLES

let selectedMovie = null;

let saved = [];

try {

    const stored = JSON.parse(
        localStorage.getItem("ralepomaSaved") || "[]"
    );

    if (Array.isArray(stored)) {

        saved = stored.filter(id =>
            Number.isInteger(id) &&
            movies.some(movie => movie.id === id)
        );

    }

} catch (error) {

    saved = [];

}

// DISPLAY MOVIES, SERIES AND CARTOONS

function displayMovies(list, container) {

    const area = document.getElementById(container);

    if (!area) return;

    area.innerHTML = "";

    if (list.length === 0) return;

    list.forEach(movie => {

        const card = document.createElement("div");

        card.className = "movie";

        card.innerHTML = `

            <div class="poster"
                 style="background:${movie.color}">

                <img
                    src="${movie.image}"
                    alt="${movie.title} poster"
                    loading="lazy"
                >

                <span class="category">
                    ${movie.type}
                </span>

                <h3>${movie.title}</h3>

            </div>

            <h4>${movie.title}</h4>

            <small>
                ${movie.genre} · ${movie.year}
            </small>

        `;

        const image = card.querySelector("img");

        image.addEventListener("error", function() {

            this.style.display = "none";

        });

        card.addEventListener("click", () => {

            openMovie(movie.id);

        });

        area.appendChild(card);

    });

}


// SEARCH AND FILTER

function refresh() {

    const searchInput = document.getElementById("search");
    const genreInput = document.getElementById("genre");
    const typeInput = document.getElementById("type");

    if (!searchInput || !genreInput || !typeInput) return;

    const query = searchInput.value.trim().toLowerCase();

    const genre = genreInput.value.toLowerCase();

    const type = typeInput.value.toLowerCase();

    const filtered = movies.filter(movie => {

        const matchesSearch =
            movie.title.toLowerCase().includes(query);

        const matchesGenre =
            genre === "all" ||
            movie.genre.toLowerCase() === genre;

        const matchesType =
            type === "all" ||
            movie.type.toLowerCase() === type;

        return matchesSearch && matchesGenre && matchesType;

    });

    // MOVIES

    displayMovies(
        filtered.filter(movie => movie.type === "Movie"),
        "movieContainer"
    );

    // SERIES

    displayMovies(
        filtered.filter(movie => movie.type === "Series"),
        "seriesContainer"
    );

    // CARTOONS

    displayMovies(
        filtered.filter(movie => movie.type === "Cartoon"),
        "cartoonContainer"
    );

    // NO RESULTS MESSAGE

    const containers = [
        "movieContainer",
        "seriesContainer",
        "cartoonContainer"
    ];

    containers.forEach(id => {

        const container = document.getElementById(id);

        if (container && container.children.length === 0) {

            const message = document.createElement("p");

            message.className = "no-results";

            message.textContent = "No titles found.";

            container.appendChild(message);

        }

    });

}

// SEARCH EVENTS

document.getElementById("search")
